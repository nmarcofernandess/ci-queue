test('table gutters, wide stages and zoom retain structural alignment',async({page})=>{
  await page.setViewportSize({width:1600,height:1000})
  await installConsistencyFixtures(page)
  await page.goto('/#status')
  await expect(page.getByRole('button',{name:'passed-run',exact:true})).toBeVisible()
  const cardTables=page.locator('table[data-placement=card]')
  for(const table of await cardTables.all()){
    const gutters=await table.evaluate(el=>{
      const card=el.closest('[data-slot=card]')!
      const header=card.querySelector('[data-slot=card-header]')!
      const first=el.querySelector('thead th:first-child')!,last=el.querySelector('thead th:last-child')!
      return { first:parseFloat(getComputedStyle(first).paddingLeft),last:parseFloat(getComputedStyle(last).paddingRight),header:parseFloat(getComputedStyle(header).paddingLeft) }
    })
    expect(gutters.first).toBe(gutters.header)
    expect(gutters.last).toBe(gutters.header)
  }
  await shot(page,'final-1600-light-stages-tables')
  await page.getByRole('textbox',{name:'Buscar por preset, branch, SHA ou ticket'}).fill('not-in-fixture')
  await expect(page.getByText('Nenhuma execução corresponde aos filtros',{exact:true})).toBeVisible()
  await shot(page,'final-1600-light-filtered-empty')
  await page.setViewportSize({width:700,height:1000})
  await page.goto('/#worktrees')
  await page.getByRole('button',{name:'example-clean',exact:true}).click()
  await inspectDrawer(page)
  await shot(page,'final-700-light-worktree')
  await closeDrawer(page)
  await page.setViewportSize({width:1440,height:1000})
  // CSS zoom exercises a doubled content scale without changing browser profiles.
  await page.evaluate(()=>{document.documentElement.style.zoom='2'})
  await page.getByRole('button',{name:'example-clean',exact:true}).click()
  const drawer=page.getByRole('dialog')
  const close=drawer.getByRole('button',{name:'Fechar worktree',exact:true})
  await expect(close).toBeVisible()
  await shot(page,'final-1440-light-worktree-zoom-200')
  await close.click()
  await expect(drawer).toHaveCount(0)
})

test('worktrees and analysis distinguish loading from errors',async({page})=>{
  await installConsistencyFixtures(page)
  let release!:()=>void
  const pending=new Promise<void>(resolve=>{release=resolve})
  await page.route('**/api/worktrees',async route=>{await pending;await route.fulfill({status:503,json:{error:'Fixture inventory unavailable'}})})
  await page.goto('/#worktrees')
  await expect(page.locator('[data-slot=skeleton]').first()).toBeVisible()
  await shot(page,'final-1440-light-worktrees-loading')
  release()
  await expect(page.getByText('Não foi possível carregar as worktrees',{exact:true})).toBeVisible()
  await shot(page,'final-1440-light-worktrees-error')
  let releaseAnalysis!:()=>void
  const analysisPending=new Promise<void>(resolve=>{releaseAnalysis=resolve})
  await page.route('**/api/analysis**',async route=>{await analysisPending;await route.fulfill({status:503,json:{error:'Fixture analysis unavailable'}})})
  await page.goto('/#analysis')
  await expect(page.locator('[data-slot=skeleton]').first()).toBeVisible()
  await shot(page,'final-1440-light-analysis-loading')
  releaseAnalysis()
  await expect(page.getByText('Não foi possível carregar os resultados',{exact:true})).toBeVisible()
  await shot(page,'final-1440-light-analysis-error')
})
